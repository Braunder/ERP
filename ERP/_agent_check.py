"""Проверка money-loop, style-групп и потенциальных проблем."""
from datetime import date
from unittest.mock import MagicMock
from app.services.report import (
    ReportData, report_to_matrix, report_layout,
    MONEY_FORMAT_FIRST_ROW, MONEY_FORMAT_LAST_ROW,
    REPORT_TEMPLATE,
)
from app.services.sheets import _format_report_sheet

ms = [date(2026, m, 1) for m in (4, 5, 6, 7, 8, 9, 10)]
rd = ReportData(months=[""] * 7, rows=[], month_starts=ms)
matrix = report_to_matrix(rd)
layout = report_layout()

print("=== 1. Money-rows непрерывность ===")
money_indices = [i for i, l in enumerate(layout) if l.get("money")]
print(f"Money rows (0-indexed): {money_indices[:5]} ... {money_indices[-5:]}")
print(f"Money row count: {len(money_indices)}")
if money_indices:
    expected = list(range(money_indices[0], money_indices[-1] + 1))
    if money_indices == expected:
        print("OK: money rows CONTIGUOUS 3..56")
    else:
        missing = set(expected) - set(money_indices)
        extra = set(money_indices) - set(expected)
        print(f"GAPS: {missing}  EXTRA: {extra}")

print("\n=== 2. Money-loop: проверка группировки ===")
money_start = None
money_ranges = []
num_rows = 61
for i in range(num_rows):
    money = layout[i]["money"]
    if money and money_start is None:
        money_start = i
    elif not money and money_start is not None:
        money_ranges.append((money_start, i))
        money_start = None
if money_start is not None:
    money_ranges.append((money_start, num_rows))

print(f"Money ranges generated by loop: {money_ranges}")
print(f"Count: {len(money_ranges)}")
assert len(money_ranges) == 1 and money_ranges[0] == (3, 57), \
    f"Expected [(3, 57)], got {money_ranges}"
print("OK: money loop produces single range (3, 57)")

print("\n=== 3. Style groups (consecutive) ===")
idx = 0
groups = []
while idx < num_rows:
    style = layout[idx]["style"]
    end = idx + 1
    while end < num_rows and layout[end]["style"] == style:
        end += 1
    groups.append((idx, end, style))
    idx = end

for s, e, sty in groups:
    if e - s > 1:
        print(f"  {s+1}-{e}: style={sty} ({e-s} rows)")

print(f"\nTotal style groups: {len(groups)}")

print("\n=== 4. Template row numbering check ===")
for i, line in enumerate(REPORT_TEMPLATE):
    row_num = i + 1
    if line.row is not None and line.row != row_num:
        print(f"MISMATCH: line {i+1} '{line.label}' has row={line.row}, expected {row_num}")
print("OK: all template lines numbered correctly")

print("\n=== 5. Formula references within template ===")
import re
ref_numbers = set()
for i, line in enumerate(REPORT_TEMPLATE):
    if line.kind == "expr" or line.kind == "sum":
        ref_str = str(line.ref)
        nums = re.findall(r"\{c\}(\d+)", ref_str)
        for n in nums:
            ref_numbers.add(int(n))

for rn in sorted(ref_numbers):
    if rn < 1 or rn > 61:
        print(f"  WARNING: formula references row {rn} (outside 1..61)")
    else:
        label = REPORT_TEMPLATE[rn - 1].label
        print(f"  Row {rn}: '{label}'")

print(f"\n=== 6. Width consistency ===")
widths = set(len(row) for row in matrix)
print(f"Row widths: {widths}")
assert widths == {9}, f"Expected width 9, got {widths}"
print("OK: all rows have 9 columns")

print("\n=== 7. Check blank rows are truly empty ===")
blank_rows = [i for i, l in enumerate(REPORT_TEMPLATE) if l.kind == "blank"]
for i in blank_rows:
    cells = set(matrix[i][1:])
    if cells != {""}:
        print(f"  ERROR: blank row {i+1} has non-empty cells: {cells}")
print(f"OK: {len(blank_rows)} blank rows verified empty")

print("\n=== 8. Summary ===")
print(f"Template lines: {len(REPORT_TEMPLATE)}")
print(f"Matrix rows: {len(matrix)}")
print(f"Matrix cols: {len(matrix[0])}")
print(f"Money rows: 3..57 (continuous)")
print(f"Style groups: {len(groups)}")
print("ALL CHECKS PASSED")
